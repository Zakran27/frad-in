'use client'

import { useCallback, useEffect, useState } from 'react'

export default function B2BGame() {
  const [punchline, setPunchline] = useState(null)
  const [answer, setAnswer] = useState(null) // null tant que pas répondu, sinon true (Real) / false (AI)
  const [error, setError] = useState(false)

  const load = useCallback(() => {
    return fetch('/api/b2b-random')
      .then((res) => (res.ok ? res.json() : Promise.reject(res.status)))
      .then((data) => {
        setPunchline(data)
        setAnswer(null)
        setError(false)
      })
      .catch(() => setError(true))
  }, [])

  useEffect(() => {
    load()
  }, [load])

  const answered = answer !== null
  const correct = answered && answer === punchline?.isReal

  return (
    <section className="min-h-[70vh] flex flex-col items-center justify-center text-center">
      <h1 className="font-display text-3xl sm:text-4xl font-extrabold tracking-tight">
        Bendo na Bendo <span aria-hidden="true">🔥</span>
      </h1>
      <p className="mt-3 text-muted">Real French rap punchline, or generated by an AI?</p>

      <div className="mt-10 w-full max-w-3xl rounded-3xl bg-ink-2 border border-line px-6 py-10 sm:px-12 sm:py-14 min-h-48 flex items-center justify-center">
        {error ? (
          <p className="text-muted">The punchline got lost. Try again in a second.</p>
        ) : punchline ? (
          <blockquote className="font-display text-2xl sm:text-4xl font-bold leading-tight text-balance [overflow-wrap:anywhere]">
            “{punchline.text}”
          </blockquote>
        ) : (
          <p className="text-muted font-mono" aria-live="polite">Loading punchline…</p>
        )}
      </div>

      {punchline && !error && (
        <div aria-live="polite" className="mt-8 w-full max-w-3xl">
          {!answered ? (
            <div className="flex justify-center gap-4">
              <button
                type="button"
                onClick={() => setAnswer(true)}
                className="min-h-12 px-8 rounded-full bg-paper text-ink font-bold text-lg hover:bg-acid active:scale-95 transition"
              >
                🎤 Real
              </button>
              <button
                type="button"
                onClick={() => setAnswer(false)}
                className="min-h-12 px-8 rounded-full bg-signal text-ink font-bold text-lg hover:brightness-110 active:scale-95 transition"
              >
                🤖 AI
              </button>
            </div>
          ) : (
            <>
              <p className={`font-display text-2xl font-bold ${correct ? 'text-acid' : 'text-signal'}`}>
                {correct ? '✅ Correct!' : '❌ Wrong!'}
              </p>
              {punchline.isReal ? (
                <p className="mt-3 text-muted">
                  Real one. 🎤 <strong className="text-paper">{punchline.artist} · {punchline.title}</strong>
                  {punchline.source && <span className="block font-mono text-sm mt-1">Source: {punchline.source}</span>}
                </p>
              ) : (
                <p className="mt-3 text-muted">🤖 Generated by an AI.</p>
              )}
              <button
                type="button"
                onClick={load}
                className="mt-6 min-h-11 px-6 rounded-full border border-line font-mono text-sm hover:bg-ink-3 active:scale-95 transition"
              >
                Next punchline 🔁
              </button>
            </>
          )}
        </div>
      )}

      {error && (
        <button
          type="button"
          onClick={load}
          className="mt-6 min-h-11 px-6 rounded-full border border-line font-mono text-sm hover:bg-ink-3"
        >
          Try again
        </button>
      )}
    </section>
  )
}
